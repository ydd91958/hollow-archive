export interface Comment {
  author: string
  time: string
  text: string
  /** 博主没有回复的评论，留白比回复更有分量。 */
  unanswered?: boolean
}

export interface Post {
  slug: string
  title: string
  date: string
  category: string
  tags: string[]
  excerpt: string
  paragraphs: string[]
  comments: Comment[]
  /** 文章里的照片。博主自己拍的、自己扫的。 */
  images?: SceneImage[]
  /**
   * 博主自己贴的站外链接。
   * 他贴气象站是为了证明那天下了雨。缺记录的事他没提，他也没看出来。
   */
  outbound?: { text: string; label: string; href: string }
  /** 访问后写入的痕迹键，用于跨站信号。 */
  traceKey?: string
}

