export const JOB_BY_ID = new Map(JOBS.map((j) => [j.id, j]))

export function getJob(id: string): Job | undefined {
  return JOB_BY_ID.get(id)
}

/** 对玩家可见的职位。带 requiresSignal 的要等信号成立。 */
export function visibleJobs(activeSignals: string[]): Job[] {
  return JOBS.filter((j) => !j.requiresSignal || activeSignals.includes(j.requiresSignal))
}

/**
 * 首页只推一线与新一线城市的职位。
 * 这既符合真实门户的运营逻辑（首页流量给大城市），
 * 也让北岭的岗位只有在检索或浏览列表时才会出现。
 */
